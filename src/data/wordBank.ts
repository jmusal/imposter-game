export const getRandomWord = (category: string): { word: string; hint: string } => {
  const cat = wordBank.find(c => c.name === category);
  if (!cat || cat.words.length === 0) {
    return { word: "Word", hint: "clue" };
  }
  const entry = cat.words[Math.floor(Math.random() * cat.words.length)];
  return entry;
};

export const getCategoryNames = (): string[] => {
  return wordBank.map(c => c.name);
};
